import math
# These are to input the X and Y value for the coordinates.
x1 = float(input("Enter x1 Value: "))
y1 = float(input("Enter y1 Value: "))
x2 = float(input("Enter x2 Value: "))
y2 = float(input("Enter y2 Value: "))


#This is to calculate the distance between the 2 coordinates.
dis = math.sqrt(pow(x2 - x1,2) + pow(y2 - y1,2))
print(dis)



